/** คลังที่แบ่งแท็บ Safety / Compliance */
export function isJpWarehouse(inventoryId: string): boolean {
  return inventoryId in JP_COMPLIANCE_CODES
}

export type JpClass = "safety" | "compliance"

export function jpClassOf(inventoryId: string, code: string): JpClass {
  return JP_COMPLIANCE_CODES[inventoryId]?.has(code) ? "compliance" : "safety"
}
